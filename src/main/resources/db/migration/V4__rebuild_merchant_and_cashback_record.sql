-- Section 7 restarts the domain: merchants carry their own cashback rate
-- and product categories are gone.
DROP TABLE cashback_record;
DROP TABLE default_cashback_rate;
DROP TABLE product_category;
DROP TABLE merchant;

CREATE TABLE merchant (
    name          VARCHAR(255)  PRIMARY KEY,
    cashback_rate NUMERIC(6, 4) NOT NULL
);

CREATE TABLE merchant_rate_change (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_name  VARCHAR(255)             NOT NULL REFERENCES merchant (name),
    cashback_rate  NUMERIC(6, 4)            NOT NULL,
    effective_from TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_merchant_rate_change_merchant_name ON merchant_rate_change (merchant_name);

CREATE TABLE cashback_record (
    purchase_id     UUID           PRIMARY KEY,
    customer_id     VARCHAR(255)   NOT NULL,
    merchant_name   VARCHAR(255)   NOT NULL,
    cashback_amount NUMERIC(19, 2) NOT NULL,
    settled         BOOLEAN        NOT NULL
);

CREATE INDEX idx_cashback_record_customer_id ON cashback_record (customer_id);
